fn glyph(c: char) -> [u8; 8] {
    match c {
        'A'..='Z' => FONT[c as usize - 'A' as usize],
        '0'..='9' => FONT[26 + c as usize - '0' as usize],
        '.' => FONT[36],
        ':' => FONT[37],
        ' ' => FONT[38],
        '>' => FONT[39],
        '\n' => FONT[40],
        _ => FONT[FONT.len() - 1], // unknown char
    }
}

/// A write-able 132x64 frame containing a buffer of monochrome pixels.
pub struct Frame {
    buffer: [u8; WIDTH * HEIGHT],
}

impl Frame {
    /// Constructs a new `Frame`.
    pub fn new() -> Self {
        Self {
            buffer: [0; WIDTH * HEIGHT],
        }
    }

    /// Clears the buffer, zero-ing out all pixels.
    pub fn clear(&mut self) {
        self.buffer = [0; WIDTH * HEIGHT];
    }

    /// Draw text at the pixel coordinates (x, y).
    ///
    /// - `text`: the text to write
    /// - `position`: the position of the text `(x, y)`
    ///
    /// If the text sequence is outside of the buffer range,
    /// the pixels are discarded and the sequence is cut off.
    pub fn draw_text(&mut self, text: &str, position: (u8, u8)) {
        let origin_x = position.0 as usize;
        let mut origin_y = position.1 as usize;
        let mut newline_count = 0;

        for (char_index, c) in text.chars().enumerate() {
            if c == '\n' {
                newline_count += 1;
                origin_y += GLYPH_HEIGHT * newline_count // move to the next line
            }

            let character = glyph(c);
            let char_x = origin_x + char_index * GLYPH_WIDTH;

            for (row, bits) in character.iter().enumerate() {
                for col in 0..GLYPH_WIDTH {
                    // most significant bit is the leftmost pixel.
                    let pixel_on = bits & (0x80 >> col) != 0;

                    let x = char_x + col;
                    let y = origin_y + row;

                    // don't write outside the framebuffer
                    if x >= WIDTH || y >= HEIGHT {
                        continue;
                    }

                    let index = y * WIDTH + x;

                    self.buffer[index] = if pixel_on { 1 } else { 0 };
                }
            }
        }
    }

    /// Returns the 132x64 monochrome pixel buffer contained in the frame.
    pub fn buffer(&self) -> [u8; WIDTH * HEIGHT] {
        self.buffer
    }
}
